// Icons supplement visible text; they must not change a control's accessible name.
export type IconName = keyof typeof icons;

export function icon(name: IconName) {
  return createElement(icons[name], {
    class: `icon${name === "busy" ? " icon-spin" : ""}`,
    "aria-hidden": "true",
    focusable: "false",
    width: 18,
    height: 18,
  });
}

export function initializeIcons() {
  for (const element of document.querySelectorAll<HTMLElement>("[data-icon]")) {
    element.prepend(icon(element.dataset.icon as IconName));
  }
}
